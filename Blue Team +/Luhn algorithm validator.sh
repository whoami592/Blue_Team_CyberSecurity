    card="${card// /}"     # spaces hata dein
    card="${card//-/}"     # dashes hata dein

    echo "[*] Input: $card"
    echo "[*] Length: ${#card} digits"
    echo

    if luhn_check "$card"; then
        echo "[+] Result: VALID (Luhn check pass)"
    else
        echo "[-] Result: INVALID (Luhn check fail)"
    fi

