usage() {
    echo "Usage: $0 <card_number>"
    echo "Example (test number): $0 4111111111111111"
    exit 1
}

luhn_check() {
    local number="$1"
    local len=${#number}
    local sum=0
    local alt=0
    local i digit

    # Sirf digits allow karein
    if [[ ! "$number" =~ ^[0-9]+$ ]]; then
        echo "[!] Error: Number mein sirf digits hone chahiye."
        return 2
    fi

    for (( i = len - 1; i >= 0; i-- )); do
        digit=${number:$i:1}
        if (( alt == 1 )); then
            digit=$(( digit * 2 ))
            if (( digit > 9 )); then
                digit=$(( digit - 9 ))
            fi
        fi
        sum=$(( sum + digit ))
        alt=$(( 1 - alt ))
    done

    if (( sum % 10 == 0 )); then
        return 0
    else
        return 1
    fi
}

